#!/usr/bin/env python3
"""Build the original minimalist PDA icon atlas and layer-aware DXML patch."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import struct
import subprocess
import tempfile
from pathlib import Path

from icon_design import ATLAS_SIZE, ATLAS_TEXTURE, build_marker_plan, render_atlas, render_preview

TARGET_XML = (
    r"ui\map_spots.xml",
    r"ui\map_spots_16.xml",
    r"ui\map_spots_mp.xml",
    r"ui\map_spots_relations.xml",
    r"ui\map_spots_complex.xml",
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def dds_header(path: Path) -> dict[str, object]:
    with path.open("rb") as stream:
        data = stream.read(128)
    if len(data) != 128 or data[:4] != b"DDS ":
        raise ValueError(f"Invalid DDS header: {path}")
    height, width = struct.unpack_from("<II", data, 12)
    mips = struct.unpack_from("<I", data, 28)[0] or 1
    fourcc = data[84:88].decode("ascii", errors="replace").rstrip("\0")
    return {"width": width, "height": height, "format": fourcc, "mip_levels": mips}


def lua_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_dxml(path: Path, plan: dict[str, dict[str, object]]) -> None:
    rule_lines: list[str] = []
    for technical_id, rule in sorted(plan.items()):
        layers = []
        for layer in rule["layers"]:
            layers.append(
                "{ texture = " + lua_quote(str(layer["texture"]))
                + f", x = {layer['x']}, y = {layer['y']}, width = {layer['width']}, height = {layer['height']} }}"
            )
        rule_lines.append(
            f"    [{lua_quote(technical_id)}] = {{ width = {rule['width']}, height = {rule['height']}, "
            f"border_width = {int(rule['width']) + 2}, border_height = {int(rule['height']) + 2}, "
            f"layers = {{ {', '.join(layers)} }} }}"
        )
    targets = "\n".join(f"    [ [[{name}]] ] = true," for name in TARGET_XML)
    joined_rules = ",\n".join(rule_lines)
    body = f'''-- Generated by tools/build_icons.py. Do not edit by hand.
-- The patch changes only known marker definitions. Binding nodes, headings,
-- location levels, scale rules, animation attributes, and z-order stay intact.
local marker_rules = {{
{joined_rules}
}}

local target_files = {{
{targets}
}}

local function patch_marker(xml_obj, marker, rule)
    xml_obj:setElementAttr(marker, {{ width = rule.width, height = rule.height, scale = 0 }})
    local layer_index = 0
    local function patch_tree(node)
        xml_obj:iterateChildren(node, function(child)
            if not xml_obj:isElement(child) then return end
            local element_name = xml_obj:getElementName(child)
            if element_name == "texture" then
                layer_index = layer_index + 1
                local layer = rule.layers[layer_index] or rule.layers[#rule.layers]
                if layer then
                    xml_obj:setText(child, layer.texture)
                    xml_obj:setElementAttr(child, {{
                        x = layer.x, y = layer.y, width = layer.width, height = layer.height,
                        r = 255, g = 255, b = 255
                    }})
                end
            else
                if element_name == "static_border" then
                    xml_obj:setElementAttr(child, {{
                        x = -1, y = -1, width = rule.border_width,
                        height = rule.border_height, scale = 0
                    }})
                end
                patch_tree(child)
            end
        end)
    end
    patch_tree(marker)
end

local function scan_tree(xml_obj, node)
    xml_obj:iterateChildren(node, function(child)
        if not xml_obj:isElement(child) then return end
        local rule = marker_rules[xml_obj:getElementName(child)]
        if rule then
            patch_marker(xml_obj, child, rule)
        else
            scan_tree(xml_obj, child)
        end
    end)
end

function on_xml_read()
    RegisterScriptCallback("on_xml_read", function(xml_file_name, xml_obj)
        if not target_files[xml_file_name] then return end
        scan_tree(xml_obj, xml_obj:getRoot())
    end)
end
'''
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8", newline="\n")


def main() -> None:
    project = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=project / "assets/manifest/icons.json")
    parser.add_argument("--output-root", type=Path, required=True, help="New MO2-ready output directory")
    parser.add_argument("--texconv", type=Path, help="DirectXTex texconv.exe; otherwise use PATH")
    parser.add_argument("--preview", type=Path, help="Optional labeled PNG preview")
    args = parser.parse_args()

    output_root = args.output_root.resolve()
    if output_root.exists():
        raise SystemExit(f"Output path must not already exist: {output_root}")
    texconv = str(args.texconv) if args.texconv else shutil.which("texconv")
    if not texconv or not Path(texconv).is_file():
        raise SystemExit("DirectXTex texconv.exe was not found; pass --texconv explicitly")
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    if manifest.get("base_marker_definition_inventory_complete") is not True:
        raise SystemExit("Refusing build: base marker definition inventory is incomplete")

    plan = build_marker_plan(manifest)
    if not plan:
        raise SystemExit("The semantic marker plan is empty")
    atlas_dir = output_root / "gamedata/textures/ui/anomalyhope/pda"
    script_path = output_root / "gamedata/scripts/modxml_anomalyhope_pda_icons.script"
    atlas_dir.mkdir(parents=True)
    write_dxml(script_path, plan)
    if args.preview:
        render_preview(args.preview.resolve())

    with tempfile.TemporaryDirectory(prefix="anomalyhope-pda-build-") as temporary_name:
        temporary = Path(temporary_name)
        source_png = temporary / "modern_icons.png"
        render_atlas(source_png)
        completed = subprocess.run(
            [texconv, "-nologo", "-y", "-dx9", "-m", "1", "-f", "DXT5", "-o", str(temporary), str(source_png)],
            capture_output=True,
            text=True,
        )
        generated = temporary / "modern_icons.dds"
        if completed.returncode or not generated.is_file():
            raise RuntimeError(f"texconv failed:\n{completed.stdout}\n{completed.stderr}")
        atlas_path = atlas_dir / "modern_icons.dds"
        shutil.copy2(generated, atlas_path)

    atlas_info = dds_header(atlas_path)
    if (atlas_info["width"], atlas_info["height"]) != (ATLAS_SIZE, ATLAS_SIZE):
        raise RuntimeError(f"Unexpected atlas dimensions: {atlas_info}")
    categories: dict[str, int] = {}
    for rule in plan.values():
        category = str(rule["category"])
        categories[category] = categories.get(category, 0) + 1
    report = {
        "game": manifest["game"],
        "method": "original minimalist semantic icon atlas",
        "atlas_texture": ATLAS_TEXTURE,
        "marker_rule_count": len(plan),
        "categories": dict(sorted(categories.items())),
        "atlas": {
            "output_file": str(atlas_path.relative_to(output_root)).replace("\\", "/"),
            **atlas_info,
            "sha256": sha256(atlas_path),
        },
    }
    (output_root / "build_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Built one original HD icon atlas and {len(plan)} semantic marker rules: {output_root}")


if __name__ == "__main__":
    main()
